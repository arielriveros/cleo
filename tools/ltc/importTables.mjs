// Import the LTC GGX fit tables (Heitz, Dupuy, Hill and Neubelt 2016, "Real-Time Polygonal-Light Shading
// with Linearly Transformed Cosines", https://github.com/selfshadow/ltc_code, fit/results/ltc.js) into
// src/graphics/ltcTables.ts, from three.js's RectAreaLightUniformsLib.js (MIT), which carries them verbatim.
//
//   node tools/ltc/importTables.mjs <path to RectAreaLightUniformsLib.js>
//
// Fetch that file from a three.js release, e.g. https://unpkg.com/three@0.160.0/examples/jsm/lights/
// RectAreaLightUniformsLib.js. The tables are 64 x 64 RGBA each, indexed (perceptual roughness,
// sqrt(1 - NoV)); they are stored as IEEE half floats, base64, about 87 KB of source.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = path.join(ROOT, 'src', 'graphics', 'ltcTables.ts');
const src = process.argv[2];
if (!src) { console.error('usage: node tools/ltc/importTables.mjs <RectAreaLightUniformsLib.js>'); process.exit(1); }
const text = fs.readFileSync(src, 'utf8');

function table(name) {
    const start = text.indexOf(`const ${name} = [`);
    const m = start < 0 ? null : [null, text.slice(text.indexOf('[', start) + 1, text.indexOf(']', start))];
    if (!m) throw new Error(`${name} not found`);
    const values = m[1].split(',').map(s => s.replace(/\s+/g, '')).filter(Boolean).map(Number);   // the source writes '- 4.5e-07'
    if (values.length !== 64 * 64 * 4 || values.some(v => !Number.isFinite(v))) throw new Error(`${name}: ${values.length} values`);
    return values;
}

// IEEE 754 binary16 from a double, round to nearest even (the tables' range is well inside it).
const f32 = new Float32Array(1), u32 = new Uint32Array(f32.buffer);
function toHalf(v) {
    f32[0] = v;
    const x = u32[0];
    const sign = (x >>> 16) & 0x8000;
    let exp = ((x >>> 23) & 0xff) - 127 + 15;
    let mant = x & 0x7fffff;
    if (exp <= 0) {
        if (exp < -10) return sign;
        mant = (mant | 0x800000) >>> (1 - exp);
        return sign | ((mant + 0x1000) >>> 13);
    }
    if (exp >= 31) return sign | 0x7c00;
    let h = sign | (exp << 10) | (mant >>> 13);
    const rest = mant & 0x1fff;
    if (rest > 0x1000 || (rest === 0x1000 && (h & 1))) h++;
    return h;
}

function encode(values) {
    const halves = new Uint16Array(values.length);
    values.forEach((v, i) => { halves[i] = toHalf(v); });
    return Buffer.from(halves.buffer).toString('base64');
}

const t1 = encode(table('LTC_MAT_1'));
const t2 = encode(table('LTC_MAT_2'));
const wrap = (s) => s.match(/.{1,120}/g).map(l => `    '${l}'`).join(' +\n');

fs.writeFileSync(OUT, `// GENERATED by tools/ltc/importTables.mjs. Do not edit by hand.
//
// The LTC GGX fit (Heitz, Dupuy, Hill and Neubelt 2016, "Real-Time Polygonal-Light Shading with Linearly
// Transformed Cosines"; https://github.com/selfshadow/ltc_code, fit/results/ltc.js), as three.js
// distributes it in examples/jsm/lights/RectAreaLightUniformsLib.js under the MIT licence
// (Copyright 2010-2023 three.js authors; see THIRD_PARTY_NOTICES.md).
//
// Two 64 x 64 RGBA tables, row-major, IEEE half floats, base64. Texel (x, y): x = perceptual roughness
// x 63, y = sqrt(1 - NoV) x 63.
//   LTC 1: the inverse transform M^-1 = [[a, 0, b], [0, 1, 0], [c, 0, d]] as (a, b, c, d)
//   LTC 2: x, y the Fresnel scale and bias (specular = f0 x x + (1 - f0) x y); z unused; w the sphere fit

/** Side of each table, texels. */
export const LTC_TABLE_SIZE = 64;

export const LTC_TABLE_1_HALF_BASE64 =
${wrap(t1)};

export const LTC_TABLE_2_HALF_BASE64 =
${wrap(t2)};
`);
console.log(`wrote ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes)`);
