// The example projects the gallery installs, from one of two places:
//
//   - A RELEASE: one zip per example on the repository's rolling `examples` release, listed in its index.json
//     (tools/examples/release.mjs; release.yml publishes it). This is every shipped editor. The web editor reads it
//     through the examples Worker (VITE_CLEO_EXAMPLES_URL), since GitHub's release downloads send no CORS headers;
//     the desktop editor asks for `examples/…` and its shell fetches that from the release (app-kit/desktop/main.js).
//     A zip is the bundle at the archive root, opened exactly as Import Project opens one.
//   - The LOCAL gallery, in dev: a project bundle folder per example under applications/editor/public/examples/<slug>/,
//     built from examples/<slug>/ by tools/examples/gallery.mjs (every editor:dev rebuilds what changed), so an
//     example's author sees their own edit. A folder is not listable over HTTP and does not need to be: the library
//     filenames are fixed and `manifest.sceneMetas` names every scene file.
//
// An index entry with a `zip` is a release entry; one without is a local folder.

/** Which build is asking: what decides where the examples come from. */
export interface ExamplesHost {
  /** The dev server (import.meta.env.DEV). */
  dev: boolean;
  /** The desktop shell (window.cleoDesktop). */
  desktop: boolean;
  /** The examples Worker the web build was made with (VITE_CLEO_EXAMPLES_URL), if any. */
  url?: string;
}

/**
 * The URL the gallery's files are read from, ending in `/`. Dev and desktop: `examples/`, relative to the document
 * (the local folders; the desktop shell's proxy of the release). The web: the examples Worker -- and without one,
 * `examples/` too, which on a deployed site finds nothing, so the gallery just does not appear.
 */
export function resolveExamplesBase(host: ExamplesHost): string {
  if (host.dev || host.desktop || !host.url) return 'examples/';
  return host.url.endsWith('/') ? host.url : `${host.url}/`;
}

function examplesBase(): string {
  return resolveExamplesBase({
    dev: !!import.meta.env.DEV,
    desktop: typeof (globalThis as any).cleoDesktop === 'object',
    url: import.meta.env.VITE_CLEO_EXAMPLES_URL,
  });
}

/** One row of the gallery's `index.json`, generated by the tools from what is actually built. */
export interface ExampleEntry {
  /** Folder name under examples/, and the stable identity of the example. */
  slug: string;
  name: string;
  description?: string;
  /** Path relative to the examples base: `<slug>-<sha8>.png` (release), `<slug>/thumbnail.png` (local). */
  thumbnail?: string;
  /** Sort key; ties fall back to name. */
  order?: number;
  /** What the user is about to download: the zip (release), the folder on disk (local). */
  bytes: number;
  sceneCount: number;
  textureCount: number;
  createdAt: number;
  /** The example's zip, relative to the examples base. Absent for a local folder. */
  zip?: string;
  /** The zip's sha256 (hex), checked before it is opened. */
  sha256?: string;
}

interface ExampleIndexFile {
  /** 1: local folders (tools/exampleKit/galleryIndex.mjs). 2: the release's zips (tools/examples/release.mjs). */
  version: 1 | 2;
  examples: ExampleEntry[];
}

/**
 * Fetch one file under the examples base, refusing an SPA fallback.
 * `editor/firebase.json` rewrites `"**" -> "/index.html"`, so a missing path returns HTTP 200 carrying the
 * editor's own HTML rather than a 404. Every response must be checked for being HTML before it is believed.
 */
async function fetchEntry(path: string): Promise<Response | null> {
  const res = await fetch(examplesBase() + path);
  if (res.status === 404) return null;
  if (!res.ok) throw new Error(`examples/${path}: HTTP ${res.status}`);
  // Content-type is the reliable tell: a real bundle entry is never text/html.
  if ((res.headers.get('content-type') ?? '').includes('text/html')) return null;
  return res;
}

async function fetchJson(path: string): Promise<any | null> {
  const res = await fetchEntry(path);
  if (!res) return null;
  const text = await res.text();
  // A static host with no content-type at all slips an HTML fallback past the check above.
  if (text.trimStart().startsWith('<')) return null;
  try {
    return JSON.parse(text);
  } catch (e: any) {
    throw new Error(`examples/${path} is not valid JSON: ${e?.message ?? e}`);
  }
}

/**
 * The catalogue of examples, in display order.
 * A missing index is NOT an error — a checkout without its examples' data, or a web build without the examples
 * Worker, has none, and the gallery simply does not appear.
 */
export async function loadExampleIndex(): Promise<ExampleEntry[]> {
  let index: ExampleIndexFile | null = null;
  try {
    index = (await fetchJson('index.json')) as ExampleIndexFile | null;
  } catch (e: any) {
    Logger.error(`Could not read the example index: ${e?.message ?? e}`, 'Editor');
    return [];
  }
  if (!index || !Array.isArray(index.examples)) return [];
  return [...index.examples].sort(
    (a, b) => (a.order ?? 0) - (b.order ?? 0) || a.name.localeCompare(b.name),
  );
}

/** The URL an `ExampleEntry.thumbnail` resolves to, or null when the example has no image. */
export function exampleThumbnailUrl(entry: ExampleEntry): string | null {
  return entry.thumbnail ? examplesBase() + entry.thumbnail : null;
}

/** Lowercase hex of the SHA-256 of `bytes`. */
async function sha256Hex(bytes: ArrayBuffer): Promise<string> {
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', bytes));
  return Array.from(digest, b => b.toString(16).padStart(2, '0')).join('');
}

const MB = 1024 * 1024;
/** Bytes as MB to one decimal: what a download's progress counts in (the loading screen prints done/total). */
const inMB = (bytes: number) => Math.round((bytes / MB) * 10) / 10;

/**
 * Download a release entry's zip, reporting progress in MB, and check it against the index's sha256: a zip that
 * does not match (truncated, or replaced under its name) is refused rather than half-opened.
 */
export async function downloadExampleZip(
  entry: ExampleEntry,
  onProgress?: (doneMB: number, totalMB: number) => void,
  base: string = examplesBase(),
): Promise<ArrayBuffer> {
  if (!entry.zip) throw new Error(`Example "${entry.slug}" has no zip`);
  const res = await fetch(base + entry.zip);
  if (!res.ok) throw new Error(`${entry.zip}: HTTP ${res.status}`);
  const total = Number(res.headers.get('content-length')) || entry.bytes || 0;
  let buffer: ArrayBuffer;
  if (!res.body) {
    buffer = await res.arrayBuffer();
  } else {
    // Read in chunks for the progress; one allocation of the known size rather than a list joined at the end,
    // since an example can be a few hundred MB.
    const reader = res.body.getReader();
    let out = new Uint8Array(total || 1 << 20);
    let received = 0;
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      if (received + value.byteLength > out.byteLength) {
        const grown = new Uint8Array(Math.max(out.byteLength * 2, received + value.byteLength));
        grown.set(out.subarray(0, received));
        out = grown;
      }
      out.set(value, received);
      received += value.byteLength;
      onProgress?.(inMB(received), inMB(Math.max(total, received)));
    }
    buffer = received === out.byteLength ? out.buffer : out.slice(0, received).buffer;
  }
  if (entry.sha256 && (await sha256Hex(buffer)) !== entry.sha256.toLowerCase()) {
    throw new Error(`${entry.zip} does not match the gallery's index (sha256): the download was cut short or the file changed`);
  }
  return buffer;
}

/** A release entry: its zip downloaded, checked and unzipped off the main thread. */
async function readZipEntry(entry: ExampleEntry, onProgress?: (done: number, total: number, unit: 'MB' | 'files') => void): Promise<BundleData> {
  const buffer = await downloadExampleZip(entry, (done, total) => onProgress?.(done, total, 'MB'));
  return importBundleBufferJob(buffer);
}

/** Read one example's folder as a bundle, exactly as if its .zip had been picked from disk. */
function fetchSource(slug: string, onEntry?: (done: number, total: number) => void): BundleSource {
  const dir = `${slug}/`;
  return {
    async json(path) {
      // Scene blobs are the one big JSON in a bundle, so they are parsed in the project worker; for
      // everything else the round trip costs more than the parse.
      if (!path.startsWith(BUNDLE_PATHS.scenesDir)) return fetchJson(dir + path);
      const res = await fetchEntry(dir + path);
      if (!res) return null;
      const buffer = await res.arrayBuffer();
      if (!buffer.byteLength || new Uint8Array(buffer)[0] === 0x3c) return null; // '<' = an HTML fallback
      return parseJsonBuffer(buffer);
    },
    async bytes(path) {
      const res = await fetchEntry(dir + path);
      return res ? await res.arrayBuffer() : null;
    },
    // No directory listing over HTTP, so the manifest is the authority on which scenes exist. Fall back to
    // nothing rather than guessing, so a malformed folder is loud instead of half-loaded.
    async scenePaths(manifest: BundleManifest) {
      return (manifest.sceneMetas ?? []).map(m => `${BUNDLE_PATHS.scenesDir}${m.id}.json`);
    },
    onEntry,
  };
}

/**
 * Download an example and open it as a brand-new project. Resolves by reloading the page, so a
 * resolved promise means "we are leaving", not "we are done".
 *
 * Nothing here may touch scoped storage: the gallery also renders on the boot launcher, where no project is
 * open and `scoped()` throws.
 */
export async function importExample(
  entry: ExampleEntry,
  /** The download's progress: MB of the zip (a release entry), or files of the folder (a local one). */
  onProgress?: (done: number, total: number, unit: 'MB' | 'files') => void,
  /** The caller already asked about unsaved work (before showing a loading screen over the dialog). */
  alreadyConfirmed = false,
  options?: { folder?: ExampleFolderTarget },
): Promise<boolean> {
  // Asked BEFORE the download: this ends in a reload into the new project, so anything unsaved in the
  // open one is lost, and finding that out after fetching several megabytes is the wrong order. On the
  // boot launcher there is no open project, so there is nothing unsaved and no dialog appears — which
  // matters, because DialogHost is mounted by the editor shell and not by the launcher.
  if (!alreadyConfirmed && !(await confirmDiscard('Opening an example'))) return false;
  const bundle = entry.zip
    ? await readZipEntry(entry, onProgress)
    : (await readBundle(fetchSource(entry.slug, (done, total) => onProgress?.(done, total, 'files')))).bundle;
  if (bundle.manifest.kind !== 'project') {
    throw new Error(`Example "${entry.slug}" is not a project bundle`);
  }
  // In the desktop app a project is a folder: the example is written into the one the user picked.
  if (options?.folder) {
    const { installBundleToFolder } = await import('../features/projectFolder/openFolder');
    return installBundleToFolder(bundle, options.folder.root, options.folder.name, {
      gitInit: options.folder.gitInit, npmInstall: options.folder.npmInstall,
    });
  }
  return applyBundleAsNewProject(bundle, entry.name, true);
}

/** Where a desktop install puts the example (the location dialog's answer). */
export interface ExampleFolderTarget { root: string; name: string; gitInit: boolean; npmInstall: boolean }

/** Human-readable download size for a card. */
export function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  const units = ['KB', 'MB', 'GB'];
  let value = bytes / 1024;
  let unit = 0;
  while (value >= 1024 && unit < units.length - 1) {
    value /= 1024;
    unit++;
  }
  return `${value < 10 ? value.toFixed(1) : Math.round(value)} ${units[unit]}`;
}
