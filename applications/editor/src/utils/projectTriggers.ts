import type { AnimationStateMachine } from 'cleo'

// The trigger names a project's animators declare, and the declaration that makes its scripts checked
// against them: with it, `animator.setTrigger('Rol')` and a `TriggerName` field set to 'Rol' are type errors
// in the script editors, and the real names complete. Triggers are a project-wide set — a script does not
// know which character it will sit on.

/** Every trigger parameter of these machines (each with its layers' — they share the table), sorted. */
export function triggerNamesOf(machines: Iterable<AnimationStateMachine | null | undefined>): string[] {
  const names = new Set<string>()
  for (const sm of machines)
    for (const p of sm?.parameters ?? []) if (p.type === 'trigger' && p.name) names.add(p.name)
  return [...names].sort()
}

/** The state machines embedded in a serialized node tree (a template's `nodeJson`): each model node's own. */
export function machinesInNodeJson(root: unknown): AnimationStateMachine[] {
  const out: AnimationStateMachine[] = []
  const walk = (n: any) => {
    if (!n || typeof n !== 'object') return
    if (n.stateMachine?.parameters) out.push(n.stateMachine)
    for (const c of n.children ?? []) walk(c)
  }
  walk(root)
  return out
}

/**
 * The generated `.cleo/types/project.d.ts`: an augmentation of the engine's `ProjectTriggers`, one key per
 * trigger, which narrows `TriggerName` to them. No triggers at all leaves it empty, and a trigger stays any
 * string — a project without animators is not locked out of `setTrigger`.
 *
 * It must be a MODULE (`export {}`): a bare `declare module` would be an ambient module, shadowing the
 * engine's real declarations instead of merging into them.
 */
export function projectTypesDeclaration(triggers: readonly string[]): string {
  if (!triggers.length) return ''
  const keys = triggers.map(t => `    ${JSON.stringify(t)}: true`).join('\n')
  return [
    '// Generated by the Cleo editor from this project\'s animators: the trigger names scripts may fire.',
    '// Rewritten whenever an animator changes; do not edit.',
    'export {}',
    '',
    "declare module 'cleo/core/scripting/fieldTypes' {",
    '  interface ProjectTriggers {',
    keys,
    '  }',
    '}',
    '',
  ].join('\n')
}
