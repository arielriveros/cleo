/**
 * VS Code's JavaScript debugger on the desktop app's debug port, which offers the game windows only
 * (app-kit/desktop/debugPort.js). A script runs as cleo-script:///<its path>.ts with its own line numbers,
 * and this folder holds it at Assets/<its path>.ts, so a URL-to-folder mapping binds breakpoints with no
 * source map. The running code has its types stripped, so content validation must be off.
 */
export function launchConfiguration(port: number = DEFAULT_DEBUG_PORT, preLaunch = false) {
  return {
    name: preLaunch ? 'Debug Cleo game' : 'Attach to the Cleo game',
    type: 'chrome',
    request: 'attach',
    port,
    urlFilter: '*play.html*',
    pathMapping: { 'cleo-script:///': '${workspaceFolder}/Assets/' },
    enableContentValidation: false,
    skipFiles: ['app://**', 'http://localhost:*/**'],
    timeout: 30000,
    ...(preLaunch ? { preLaunchTask: 'cleo: debug' } : {}),
  }
}

