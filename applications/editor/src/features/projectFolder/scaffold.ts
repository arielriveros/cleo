/** Image and audio extensions as case-insensitive git globs ('png' -> '*.[pP][nN][gG]'). */
const anyCase = (ext: string) => '*.' + [...ext].map(c => (/[a-z]/i.test(c) ? `[${c.toLowerCase()}${c.toUpperCase()}]` : c)).join('')
const LFS_EXTS = ['png', 'jpg', 'jpeg', 'webp', 'gif', 'bmp', 'tga', 'tiff', 'ktx2', 'hdr', 'exr', 'avif',
  'wav', 'mp3', 'ogg', 'm4a', 'flac', 'aac', 'opus', 'webm']
const TEXT_EXTS = ['cleo', 'json', 'meta', 'ts', 'mat', 'tmat', 'tpl', 'model', 'scene', 'blendspace', 'anim', 'rig',
  'tileset', 'brain', 'animator', 'mask', 'pose', 'vfx', 'sequence', 'tex', 'sound']

export const GITATTRIBUTES = [
  '# Cleo: text stays LF everywhere; binaries go through Git LFS (git lfs install, once per machine).',
  '* text=auto eol=lf',
  ...TEXT_EXTS.map(ext => `*.${ext} text eol=lf`),
  'Blobs/** filter=lfs diff=lfs merge=lfs -text',
  'Baked/** filter=lfs diff=lfs merge=lfs -text',
  'Derived/** filter=lfs diff=lfs merge=lfs -text',
  ...LFS_EXTS.map(ext => `${anyCase(ext)} filter=lfs diff=lfs merge=lfs -text`),
  '',
].join('\n')

