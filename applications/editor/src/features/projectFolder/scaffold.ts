// The tooling a folder project carries around its data, so it works as a TypeScript and git project on its own:
//
//   package.json        npm scripts: typecheck, watch, play, debug, test
//   tsconfig.json       the in-editor script editor's options, @/ mapped onto Assets/
//   vitest.config.mjs   script unit tests under tests/, against the headless engine (the SDK)
//   .vscode/            hides the editor's files, "Debug Cleo game" (F5) and its tasks
//   .gitignore          .cleo/ and node_modules/ are regenerable
//   .gitattributes      LF text for JSON and metas; images, audio, Blobs/, Baked/ and Derived/ through Git LFS
//   README.md           what the folder is and how to work with it
//
// Each is written ONCE, where none exists (`keep`), because the user may make it their own — except the two
// that carry a generated header, which are rewritten while the header is still there.
//
// Pure text: the main process writes them (projectFolder.js writeScaffold, which allows tooling paths only).

import { getEditorPrefs } from '../options/editorPrefs'
import { requireProjectBridge } from './desktopProject'

export const DEFAULT_DEBUG_PORT = 9339

/** The marker of a file the editor still owns and may rewrite. */
export const GENERATED_HEADER = '// Generated by the Cleo editor.'

/** The versions `npm install` pins for the project's script tooling. */
const TYPESCRIPT_VERSION = '~5.6.3'
const VITEST_VERSION = '^3.2.4'

export function packageJson(name: string): string {
  const slug = name.toLowerCase().replace(/[^a-z0-9._-]+/g, '-').replace(/^[-._]+|[-._]+$/g, '') || 'cleo-game'
  return JSON.stringify({
    name: slug,
    private: true,
    type: 'module',
    scripts: {
      typecheck: 'tsc --noEmit -p .',
      watch: 'tsc --noEmit -p . --watch --preserveWatchOutput',
      // The CLI ships with the editor (.cleo/sdk is written whenever the project opens), so playing needs no
      // npm install.
      play: 'node .cleo/sdk/cleo/bin/cleo.mjs play',
      debug: 'node .cleo/sdk/cleo/bin/cleo.mjs play --debug',
      test: 'vitest run',
      'test:watch': 'vitest',
    },
    devDependencies: {
      cleo: 'file:.cleo/sdk/cleo',
      typescript: TYPESCRIPT_VERSION,
      vitest: VITEST_VERSION,
    },
  }, null, 2) + '\n'
}

/**
 * Must mirror monacoSetup's compiler options exactly, so the IDE and the in-editor editor agree. Committed in
 * full (no `extends` into .cleo/: a fresh clone has none until Cleo opens it, and CI must typecheck anyway).
 */
export const TSCONFIG = `${GENERATED_HEADER} Edit freely: once this header line is gone, Cleo leaves the file alone.
//
// These options mirror the editor's in-app script editor, so what you see here is what the editor sees.
// Scripts are transpiled at load time (types are stripped, never checked at runtime), so nothing emits.
{
  "compilerOptions": {
    "target": "ES2020",
    "module": "ESNext",
    "moduleResolution": "node",
    "lib": ["ES2020", "DOM"],
    "strict": false,
    "noImplicitAny": false,
    "strictNullChecks": false,
    "noImplicitThis": false,
    "skipLibCheck": true,
    "noEmit": true,
    "forceConsistentCasingInFileNames": true,
    // Scripts import each other by project path: '@/Shared/Math' is Assets/Shared/Math.ts (Shared/Math in
    // the editor's Assets panel). Relative './Util' imports work too. Deliberately no baseUrl: it would let
    // a bare 'Shared/Math' type-check here, which the game itself would not accept.
    "paths": { "@/*": ["./Assets/*"] }
  },
  // The ambient declarations are named explicitly: a "**/*" glob does not match a dot-directory.
  "include": ["Assets/**/*.ts", "tests/**/*.ts", ".cleo/types/*.d.ts"],
  "exclude": ["node_modules"]
}
`

export const VITEST_CONFIG = `${GENERATED_HEADER} Edit freely: once this header line is gone, Cleo leaves the file alone.
// Script tests: tests/**/*.test.ts, in Node, against the headless engine (cleo/testing).
import { cleoVitest } from 'cleo/testing/vitest'

export default cleoVitest()
`

