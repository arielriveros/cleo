// Publish-time transform: pull node scripts out of the game data and emit them as real functions in a
// separate game.scripts.js, so the published game parses them as normal JS instead of eval-ing strings.
// The factory body comes from the engine's buildFactoryBody — the same function the editor's eval path
// uses — which also rewrites the script's `import` statements into `__cleoImport(...)` calls.
// Obfuscation lives in ./obfuscate because that runs in the project worker, which cannot import `cleo`.

import { buildFactoryBody } from 'cleo';

export type ScriptMap = Record<string, string>;

// Walk the scene tree (root included) collecting `{ nodeId: script }` and stripping `script` from the
// nodes, so the packed game data contains no script strings. Script MODULES (`data.modules`, shared code
// scripts import) are taken out the same way, along with each node's `scriptPath`: the factories below
// are compiled with their imports already resolved, so the shipped data needs neither.
export function extractScripts(data: any): { data: any; scripts: ScriptMap; paths: ScriptMap; modules: ScriptMap } {
  const scripts: ScriptMap = {};
  const paths: ScriptMap = {};
  const modules: ScriptMap = { ...(data?.modules ?? {}) };
  if (data && 'modules' in data) delete data.modules;

  const visit = (node: any): void => {
    if (node && typeof node === 'object') {
      if (typeof node.script === 'string' && node.script.trim() && node.id) {
        scripts[node.id] = node.script;
        if (typeof node.scriptPath === 'string') paths[node.id] = node.scriptPath;
        delete node.script;
      }
      delete node.scriptPath;
      for (const child of (node.children ?? [])) visit(child);
    }
  };

  if (data?.scene) visit(data.scene);                       // v1: single scene
  if (data?.scenes) for (const s of Object.values<any>(data.scenes)) visit(s?.scene); // v2: every scene
  // Templates too, keyed by their template-internal node ids. Scene.instantiate stamps that id onto each
  // copy as `__sourceId` when it renumbers, which is how a node created at runtime finds its factory here.
  if (data?.templates) for (const t of data.templates) visit(t?.node);
  return { data, scripts, paths, modules };
}

// Build the plain (readable) game.scripts.js source. Scripts that fail to compile are skipped (with a
// warning) so one broken script can't break the whole file's parse.
//
// Node scripts go in CLEO_GAME_SCRIPTS keyed by node id; script modules in CLEO_GAME_MODULES keyed by
// module id ('/Shared/Math'), which the player hands to setScriptModuleProvider. Both are compiled with
// their own path, so relative imports are already canonical ids in the emitted code.
export function buildScriptsSource(scripts: ScriptMap, paths: ScriptMap = {}, modules: ScriptMap = {}): string {
  const lines: string[] = [
    '// Generated by Cleo publish. Node scripts and script modules as real functions (no runtime eval of JSON strings).',
    'window.CLEO_GAME_SCRIPTS = window.CLEO_GAME_SCRIPTS || {};',
    'window.CLEO_GAME_MODULES = window.CLEO_GAME_MODULES || {};',
  ];

  for (const [id, script] of Object.entries(modules)) {
    let source: string;
    try {
      source = `function(__cleoImport, __cleoExports) {\n${buildFactoryBody(script, { path: id, mode: 'module' })}\n}`;
      // eslint-disable-next-line no-new-func
      new Function(`return (${source});`);
    } catch (e) {
      lines.push(`// skipped script module ${id}: ${String((e as any)?.message || e).replace(/\n/g, ' ')}`);
      continue;
    }
    lines.push(`window.CLEO_GAME_MODULES[${JSON.stringify(id)}] = ${source};`);
  }

  for (const [id, script] of Object.entries(scripts)) {
    let source: string;
    try {
      // buildFactoryBody throws on unsupported module syntax; `new Function` catches plain syntax errors.
      source = `function(__cleoImport, __cleoExports) {\n${buildFactoryBody(script, { path: paths[id] })}\n}`;
      // eslint-disable-next-line no-new-func
      new Function(`return (${source});`);
    } catch (e) {
      lines.push(`// skipped script for ${id}: ${String((e as any)?.message || e).replace(/\n/g, ' ')}`);
      continue;
    }
    lines.push(`window.CLEO_GAME_SCRIPTS[${JSON.stringify(id)}] = ${source};`);
  }

  return lines.join('\n') + '\n';
}

